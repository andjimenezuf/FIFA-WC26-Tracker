"""The real, final 2026 World Cup — all 104 matches, 48 teams, and every
match's goal/card/substitution events — loaded once from the JSON this
package ships:

- data/matches_2026.json, data/teams_2026.json — generated by
  frontend/scripts/export-results-2026.ts from the same source of truth that
  powers the frontend's bracket. Re-run it if bracket-2026-data.ts changes.
- data/timeline_2026.json — generated by scripts/export_timeline_2026.py, a
  one-time historical pull from ESPN's match-summary feed. Re-run it only if
  that data is ever found to need correcting.

No network calls at runtime, no forecasting model: the tournament is over,
so every match is a known fact, not something to predict.
"""

import json
from pathlib import Path
from typing import Literal, Optional, TypedDict

_DATA_DIR = Path(__file__).parent / "data"

FINAL_MATCH_NUMBER = 104
GROUP_LETTERS = list("ABCDEFGHIJKL")


class TeamSide(TypedDict):
    code: str
    name: str
    score: Optional[int]


class Match(TypedDict):
    number: int
    round: str
    group: Optional[str]
    home: TeamSide
    away: TeamSide
    winner: Optional[Literal["home", "away", "draw"]]
    kickoffAt: str
    venue: str
    venueTz: Optional[str]


class TeamInfo(TypedDict):
    code: str
    name: str
    group: str
    outcome: str


class MatchEvent(TypedDict):
    minute: Optional[str]
    type: str  # "goal" | "own_goal" | "penalty_goal" | "yellow_card" | "red_card" | "substitution"
    team: str  # FIFA code when resolved, else ESPN's raw team name
    player: Optional[str]


def _load() -> tuple[dict[int, Match], dict[str, TeamInfo], dict[int, list[MatchEvent]]]:
    matches_raw: list[Match] = json.loads((_DATA_DIR / "matches_2026.json").read_text())
    teams_raw: list[TeamInfo] = json.loads((_DATA_DIR / "teams_2026.json").read_text())
    timeline_raw: dict[str, list[MatchEvent]] = json.loads(
        (_DATA_DIR / "timeline_2026.json").read_text()
    )
    return (
        {m["number"]: m for m in matches_raw},
        {t["code"]: t for t in teams_raw},
        {int(k): v for k, v in timeline_raw.items()},
    )


MATCHES, TEAMS, TIMELINES = _load()

TOURNAMENT_END_ISO = MATCHES[FINAL_MATCH_NUMBER]["kickoffAt"]

# Final placement, worst (least decided) first — used to rank "top N" and sort
# a group's qualifiers for `outlook`. Anything not listed (shouldn't happen —
# every team's outcome is one of these) sorts last.
_OUTCOME_RANK = {
    "World Cup winners": 0,
    "Runners-up": 1,
    "Third place": 2,
    "Fourth place": 3,
    "Eliminated in the quarterfinals": 4,
    "Eliminated in the round of 16": 5,
    "Eliminated in the round of 32": 6,
    "Eliminated in the group stage": 7,
}


def outcome_rank(code: str) -> int:
    team = TEAMS.get(code)
    return _OUTCOME_RANK.get(team["outcome"], 99) if team else 99


def team_code_by_name_or_code(query: str) -> Optional[str]:
    """Resolves a team name or FIFA code (any case) to its code, or None."""
    needle = query.strip().casefold()
    for code, team in TEAMS.items():
        if needle == code.casefold() or needle == team["name"].casefold():
            return code
    return None


def matches_for_team(code: str) -> list[Match]:
    """A team's real matches, group stage through elimination, in order."""
    return sorted(
        (
            m
            for m in MATCHES.values()
            if m["home"]["code"] == code or m["away"]["code"] == code
        ),
        key=lambda m: m["number"],
    )


def group_matches(letter: str) -> list[Match]:
    return [m for m in MATCHES.values() if m["group"] == letter]


class Standing(TypedDict):
    code: str
    name: str
    played: int
    won: int
    drawn: int
    lost: int
    goalsFor: int
    goalsAgainst: int
    goalDiff: int
    points: int


def _blank_standing(code: str) -> Standing:
    team = TEAMS[code]
    return Standing(
        code=code,
        name=team["name"],
        played=0,
        won=0,
        drawn=0,
        lost=0,
        goalsFor=0,
        goalsAgainst=0,
        goalDiff=0,
        points=0,
    )


def compute_standings(letter: str) -> list[Standing]:
    """One group's final table, best first. Mirrors lib/tournament/standings.ts's
    computeStandings — points, then goal difference, then goals for; matches with
    no recorded score (the handful of dead-rubber group games between two teams
    already eliminated either way) simply don't contribute, same as an unplayed
    fixture would have."""
    codes = sorted(
        {m["home"]["code"] for m in group_matches(letter)}
        | {m["away"]["code"] for m in group_matches(letter)}
    )
    table = {code: _blank_standing(code) for code in codes}

    for m in group_matches(letter):
        h, a = m["home"]["score"], m["away"]["score"]
        if h is None or a is None:
            continue
        home, away = table[m["home"]["code"]], table[m["away"]["code"]]
        home["played"] += 1
        away["played"] += 1
        home["goalsFor"] += h
        home["goalsAgainst"] += a
        away["goalsFor"] += a
        away["goalsAgainst"] += h
        if h > a:
            home["won"] += 1
            home["points"] += 3
            away["lost"] += 1
        elif a > h:
            away["won"] += 1
            away["points"] += 3
            home["lost"] += 1
        else:
            home["drawn"] += 1
            away["drawn"] += 1
            home["points"] += 1
            away["points"] += 1

    for s in table.values():
        s["goalDiff"] = s["goalsFor"] - s["goalsAgainst"]

    return sorted(
        table.values(),
        key=lambda s: (-s["points"], -s["goalDiff"], -s["goalsFor"], s["code"]),
    )


class ThirdPlace(TypedDict):
    group: str
    code: str
    name: str
    points: int
    goalDiff: int
    goalsFor: int
    rank: int
    qualifies: bool


def rank_thirds() -> list[ThirdPlace]:
    """The twelve third-placed teams ranked by FIFA's criteria (points → goal
    difference → goals for → group letter); the best eight qualified for the
    Round of 32. Since every group is final, this is the real historical
    ranking, not a projection."""
    thirds = []
    for letter in GROUP_LETTERS:
        third = compute_standings(letter)[2]
        thirds.append({"group": letter, **third})
    thirds.sort(key=lambda t: (-t["points"], -t["goalDiff"], -t["goalsFor"], t["group"]))
    return [
        ThirdPlace(
            group=t["group"],
            code=t["code"],
            name=t["name"],
            points=t["points"],
            goalDiff=t["goalDiff"],
            goalsFor=t["goalsFor"],
            rank=i + 1,
            qualifies=i < 8,
        )
        for i, t in enumerate(thirds)
    ]
